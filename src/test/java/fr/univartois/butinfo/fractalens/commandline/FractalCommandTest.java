package fr.univartois.butinfo.fractalens.commandline;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import fr.univartois.butinfo.fractalens.complex.ImageType;
import fr.univartois.butinfo.fractalens.complex.sequence.AllSequences;
import fr.univartois.butinfo.fractalens.palette.AllPalettes;

import picocli.CommandLine;

/**
 * The FractalCommandTest tests the command-line interface implemented by
 * {@link FractalCommand}.
 * The images generated by these tests are very small (few pixels and iterations),
 * so that the tests stay fast.
 *
 * @author Your Name
 *
 * @version 0.1.0
 */
class FractalCommandTest {

    /**
     * The exit code returned by picocli when everything went well.
     */
    private static final int OK = 0;

    /**
     * The exit code returned by picocli when the command line is invalid.
     */
    private static final int USAGE_ERROR = 2;

    /**
     * The message displayed at the beginning of the help of the application.
     */
    private static final String USAGE = "Usage: fractalens";

    /**
     * The directory in which the tests write their images.
     */
    @TempDir
    Path tempDir;

    /**
     * Creates a new command line for the application.
     *
     * @param out The writer in which the standard output is captured.
     * @param err The writer in which the error output is captured.
     *
     * @return The created command line.
     */
    private static CommandLine createCommandLine(StringWriter out, StringWriter err) {
        CommandLine commandLine = new CommandLine(new FractalCommand());
        commandLine.setOut(new PrintWriter(out));
        commandLine.setErr(new PrintWriter(err));
        return commandLine;
    }

    /**
     * Executes the application with the given arguments.
     *
     * @param out The writer in which the standard output is captured.
     * @param err The writer in which the error output is captured.
     * @param args The arguments of the command line.
     *
     * @return The exit code of the application.
     */
    private static int execute(StringWriter out, StringWriter err, String... args) {
        return createCommandLine(out, err).execute(args);
    }

    /**
     * Executes the application with the given arguments, ignoring its outputs.
     *
     * @param args The arguments of the command line.
     *
     * @return The exit code of the application.
     */
    private static int execute(String... args) {
        return execute(new StringWriter(), new StringWriter(), args);
    }

    /**
     * Parses the given arguments, without executing the application.
     *
     * @param args The arguments of the command line.
     *
     * @return The command line, after the parsing of the arguments.
     */
    private static CommandLine parse(String... args) {
        CommandLine commandLine = createCommandLine(new StringWriter(), new StringWriter());
        commandLine.parseArgs(args);
        return commandLine;
    }

    /**
     * Gets the value read for an option of the command line.
     *
     * @param commandLine The command line, after the parsing of the arguments.
     * @param option The name of the option.
     *
     * @return The value of the option.
     */
    private static Object valueOf(CommandLine commandLine, String option) {
        return commandLine.getCommandSpec().findOption(option).getValue();
    }

    /**
     * Gets the path of a file in the temporary directory of the tests.
     *
     * @param name The name of the file.
     *
     * @return The path of the file, as a string.
     */
    private String path(String name) {
        return tempDir.resolve(name).toString();
    }

    /**
     * Checks that a file has been created and is not empty.
     *
     * @param name The name of the file.
     *
     * @throws IOException If the size of the file cannot be read.
     */
    private void assertFileCreated(String name) throws IOException {
        Path file = tempDir.resolve(name);
        assertTrue(Files.exists(file));
        assertTrue(Files.size(file) > 0);
    }

    /**
     * Test method for the default values of the options of {@link FractalCommand}.
     */
    @Test
    void testDefaultValues() {
        CommandLine commandLine = parse("-f", "MANDELBROT", "-o", "out.png");

        assertEquals(AllSequences.MANDELBROT, valueOf(commandLine, "-f"));
        assertEquals(250, valueOf(commandLine, "-n"));
        assertEquals(600, valueOf(commandLine, "-h"));
        assertEquals(800, valueOf(commandLine, "-w"));
        assertEquals(0.004, valueOf(commandLine, "-s"));
        assertEquals(0.0, valueOf(commandLine, "-x"));
        assertEquals(0.0, valueOf(commandLine, "-y"));
        assertEquals(AllPalettes.GREYSCALE, valueOf(commandLine, "-p"));
        assertEquals(ImageType.SINGLE, valueOf(commandLine, "-t"));
        assertEquals(30, valueOf(commandLine, "-i"));
        assertEquals("out.png", valueOf(commandLine, "-o"));
    }

    /**
     * Test method for the short names of the options of {@link FractalCommand}.
     */
    @Test
    void testShortOptions() {
        CommandLine commandLine = parse("-f", "JULIA", "-n", "100", "-h", "50", "-w", "70",
                "-s", "0.01", "-x", "-0.5", "-y", "0.25", "-p", "GREYSCALE",
                "-t", "ZOOM", "-i", "5", "-o", "anim.gif");

        assertEquals(AllSequences.JULIA, valueOf(commandLine, "-f"));
        assertEquals(100, valueOf(commandLine, "-n"));
        assertEquals(50, valueOf(commandLine, "-h"));
        assertEquals(70, valueOf(commandLine, "-w"));
        assertEquals(0.01, valueOf(commandLine, "-s"));
        assertEquals(-0.5, valueOf(commandLine, "-x"));
        assertEquals(0.25, valueOf(commandLine, "-y"));
        assertEquals(AllPalettes.GREYSCALE, valueOf(commandLine, "-p"));
        assertEquals(ImageType.ZOOM, valueOf(commandLine, "-t"));
        assertEquals(5, valueOf(commandLine, "-i"));
        assertEquals("anim.gif", valueOf(commandLine, "-o"));
    }

    /**
     * Test method for the long names of the options of {@link FractalCommand}.
     */
    @Test
    void testLongOptions() {
        CommandLine commandLine = parse("--fractal-name", "JULIA", "--nb-iterations", "100",
                "--height", "50", "--width", "70", "--scale", "0.01",
                "--focus-x", "-0.5", "--focus-y", "0.25", "--palette-name", "GREYSCALE",
                "--type", "ROTATION", "--image-count", "5", "--output", "anim.gif");

        assertEquals(AllSequences.JULIA, valueOf(commandLine, "-f"));
        assertEquals(100, valueOf(commandLine, "-n"));
        assertEquals(50, valueOf(commandLine, "-h"));
        assertEquals(70, valueOf(commandLine, "-w"));
        assertEquals(0.01, valueOf(commandLine, "-s"));
        assertEquals(-0.5, valueOf(commandLine, "-x"));
        assertEquals(0.25, valueOf(commandLine, "-y"));
        assertEquals(AllPalettes.GREYSCALE, valueOf(commandLine, "-p"));
        assertEquals(ImageType.ROTATION, valueOf(commandLine, "-t"));
        assertEquals(5, valueOf(commandLine, "-i"));
        assertEquals("anim.gif", valueOf(commandLine, "-o"));
    }

    /**
     * Test method for the help message displayed by {@link FractalCommand}.
     */
    @Test
    void testHelp() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();

        assertEquals(OK, execute(out, err, "--help"));

        String help = out.toString();
        assertTrue(help.contains(USAGE));
        assertTrue(help.contains("--fractal-name"));
        assertTrue(help.contains("--nb-iterations"));
        assertTrue(help.contains("--height"));
        assertTrue(help.contains("--width"));
        assertTrue(help.contains("--scale"));
        assertTrue(help.contains("--focus-x"));
        assertTrue(help.contains("--focus-y"));
        assertTrue(help.contains("--palette-name"));
        assertTrue(help.contains("--type"));
        assertTrue(help.contains("--image-count"));
        assertTrue(help.contains("--output"));
    }

    /**
     * Test method for the message displayed by {@link FractalCommand} in case of
     * misuse: it must describe all the options, in English.
     */
    @Test
    void testUsageErrorDescribesAllOptions() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err));

        String usage = err.toString();
        assertTrue(usage.contains("-f, --fractal-name"));
        assertTrue(usage.contains("-n, --nb-iterations"));
        assertTrue(usage.contains("-h, --height"));
        assertTrue(usage.contains("-w, --width"));
        assertTrue(usage.contains("-s, --scale"));
        assertTrue(usage.contains("-x, --focus-x"));
        assertTrue(usage.contains("-y, --focus-y"));
        assertTrue(usage.contains("-p, --palette-name"));
        assertTrue(usage.contains("-t, --type"));
        assertTrue(usage.contains("-i, --image-count"));
        assertTrue(usage.contains("-o, --output"));
        assertTrue(usage.contains("The fractal to generate"));
        assertTrue(usage.contains("The file in which"));
        assertTrue(usage.contains("The maximum number of iterations"));
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when no argument
     * or a required option is missing.
     */
    @Test
    void testMissingOptions() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err));
        assertTrue(err.toString().contains(USAGE));

        err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err, "-o", path("a.png")));
        assertTrue(err.toString().contains(USAGE));

        err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err, "-f", "MANDELBROT"));
        assertTrue(err.toString().contains(USAGE));
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when an option is
     * unknown or has an invalid value.
     */
    @Test
    void testInvalidOptions() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        assertEquals(USAGE_ERROR,
                execute(out, err, "-f", "MANDELBROT", "-o", path("a.png"), "--unknown"));
        assertTrue(err.toString().contains(USAGE));

        assertEquals(USAGE_ERROR, execute("-f", "NOT_A_FRACTAL", "-o", path("a.png")));
        assertEquals(USAGE_ERROR,
                execute("-f", "MANDELBROT", "-p", "NOT_A_PALETTE", "-o", path("a.png")));
        assertEquals(USAGE_ERROR,
                execute("-f", "MANDELBROT", "-t", "NOT_A_TYPE", "-o", path("a.png")));
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when a numeric option
     * is not given a number.
     */
    @Test
    void testNotANumber() {
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-n", "abc"));
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-h", "abc"));
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-w", "abc"));
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-i", "abc"));
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-s", "abc"));
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-x", "abc"));
        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-o", path("a.png"), "-y", "abc"));
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when the size of the
     * image is invalid.
     */
    @Test
    void testInvalidSize() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err, "-f", "MANDELBROT", "-w", "0",
                "-o", path("a.png")));
        assertTrue(err.toString().contains(USAGE));

        assertEquals(USAGE_ERROR, execute("-f", "MANDELBROT", "-h", "0", "-o", path("a.png")));
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when an animation
     * has less than two images.
     */
    @Test
    void testInvalidImageCount() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err, "-f", "MANDELBROT", "-t", "ZOOM",
                "-i", "1", "-o", path("a.gif")));
        assertTrue(err.toString().contains("at least 2 images"));

        err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err, "-f", "JULIA", "-t", "ROTATION",
                "-i", "1", "-o", path("a.gif")));
        assertTrue(err.toString().contains("at least 2 images"));
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when a rotation is
     * requested for a fractal that does not support it.
     */
    @Test
    void testRotationNotSupported() {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        assertEquals(USAGE_ERROR, execute(out, err, "-f", "MANDELBROT", "-t", "ROTATION",
                "-i", "3", "-o", path("a.gif")));
        assertTrue(err.toString().contains("only available for JULIA and JULIA_GENERALIZED"));
    }

    /**
     * Test method for the generation of a single image by
     * {@link fr.univartois.butinfo.fractalens.commandline.FractalCommand#run()}.
     *
     * @throws IOException If the size of a generated file cannot be read.
     */
    @Test
    void testRunSingle() throws IOException {
        assertEquals(OK, execute("-f", "MANDELBROT", "-n", "10", "-w", "20", "-h", "15",
                "-o", path("single.png")));
        assertFileCreated("single.png");

        assertEquals(OK, execute("-f", "JULIA", "-n", "10", "-w", "20", "-h", "15",
                "-s", "0.01", "-x", "-0.5", "-y", "0.25", "-p", "GREYSCALE",
                "-t", "SINGLE", "-o", path("full.png")));
        assertFileCreated("full.png");

        // The number of images is ignored for a single image.
        assertEquals(OK, execute("-f", "MANDELBROT", "-n", "10", "-w", "20", "-h", "15",
                "-i", "1", "-t", "SINGLE", "-o", path("ignored.png")));
        assertFileCreated("ignored.png");
    }

    /**
     * Test method for the generation of a zoom by
     * {@link fr.univartois.butinfo.fractalens.commandline.FractalCommand#run()}.
     *
     * @throws IOException If the size of a generated file cannot be read.
     */
    @Test
    void testRunZoom() throws IOException {
        assertEquals(OK, execute("-f", "MANDELBROT", "-n", "10", "-w", "20", "-h", "15",
                "-t", "ZOOM", "-i", "3", "-o", path("zoom.gif")));
        assertFileCreated("zoom.gif");

        assertEquals(OK, execute("-f", "MANDELBROT", "-n", "10", "-w", "20", "-h", "15",
                "-t", "ZOOM", "-i", "2", "-o", path("zoom2.gif")));
        assertFileCreated("zoom2.gif");
    }

    /**
     * Test method for the generation of a rotation by
     * {@link fr.univartois.butinfo.fractalens.commandline.FractalCommand#run()}.
     *
     * @throws IOException If the size of a generated file cannot be read.
     */
    @Test
    void testRunRotation() throws IOException {
        assertEquals(OK, execute("-f", "JULIA", "-n", "10", "-w", "20", "-h", "15",
                "-t", "ROTATION", "-i", "3", "-o", path("julia.gif")));
        assertFileCreated("julia.gif");

        assertEquals(OK, execute("-f", "JULIA_GENERALIZED", "-n", "10", "-w", "20", "-h", "15",
                "-t", "ROTATION", "-i", "3", "-o", path("julia_generalized.gif")));
        assertFileCreated("julia_generalized.gif");
    }

    /**
     * Test method for the generation of an image by {@link FractalCommand}, for every
     * fractal of {@link AllSequences}.
     *
     * @throws IOException If the size of a generated file cannot be read.
     */
    @Test
    void testRunAllFractals() throws IOException {
        for (AllSequences sequence : AllSequences.values()) {
            String name = sequence.name().toLowerCase() + ".png";
            assertEquals(OK, execute("-f", sequence.name(), "-n", "10", "-w", "20", "-h", "15",
                    "-o", path(name)));
            assertFileCreated(name);
        }
    }

    /**
     * Test method for the generation of an image by {@link FractalCommand}, for every
     * palette of {@link AllPalettes}.
     *
     * @throws IOException If the size of a generated file cannot be read.
     */
    @Test
    void testRunAllPalettes() throws IOException {
        for (AllPalettes palette : AllPalettes.values()) {
            String name = palette.name().toLowerCase() + ".png";
            assertEquals(OK, execute("-f", "MANDELBROT", "-n", "10", "-w", "20", "-h", "15",
                    "-p", palette.name(), "-o", path(name)));
            assertFileCreated(name);
        }
    }

    /**
     * Test method for the behavior of {@link FractalCommand} when a rotation is
     * requested for every fractal that is not a Julia's sequence.
     */
    @Test
    void testRotationNotSupportedForOtherFractals() {
        for (AllSequences sequence : AllSequences.values()) {
            if (sequence == AllSequences.JULIA || sequence == AllSequences.JULIA_GENERALIZED) {
                continue;
            }
            assertEquals(USAGE_ERROR, execute("-f", sequence.name(), "-t", "ROTATION",
                    "-i", "3", "-o", path("rotation.gif")));
        }
    }

}